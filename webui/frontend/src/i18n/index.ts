export const DICTIONARIES: Record<Locale, Record<MessageKey, string>> = { zh, en }

/** 翻译 key（`{name}` 占位符按 params 替换） */
export function translate(
  locale: Locale,
  key: MessageKey,
  params?: Record<string, string | number>,
): string {
  const table = DICTIONARIES[locale] ?? zh
  let text = table[key] ?? zh[key] ?? key
  if (params) {
    for (const [name, value] of Object.entries(params)) {
      text = text.split(`{${name}}`).join(String(value))
    }
  }
  return text
}

/** 组件内使用：`const t = useT(); t('menu.logs')` */
export function useT() {
  const locale = useUiStore((s) => s.locale)
  return useCallback(
    (key: MessageKey, params?: Record<string, string | number>) =>
      translate(locale, key, params),
    [locale],
  )
}

/** 当前界面语言（日期/数字格式化用） */
export function useLocale(): Locale {
  return useUiStore((s) => s.locale)
}

/** 非组件代码（如 event handler / class）使用当前 locale 翻译 */
export function tNow(key: MessageKey, params?: Record<string, string | number>): string {
  return translate(useUiStore.getState().locale, key, params)
}
